/**
 * A hand is an alphabet plus the way it sits on the page: how wide a space is,
 * how heavy the ink runs, how far it leans, and how much room its extenders
 * need. Two hands ship, and they are the same component with different pens.
 */
interface Hand {
  glyphs: Record<string, Glyph>;
  /** Width of a space, and of any character the alphabet does not carry. */
  space: number;
  /** Ink width, in glyph units, so it scales with the type step. */
  strokeWidth: number;
  /**
   * Counter-shear, in degrees. Both scripts are drawn leaning forward; standing
   * them up a little steadies them against upright UI copy, and too much tips
   * the letters over backwards.
   */
  upright: number;
  /** How far the ink reaches above and below the baseline. */
  top: number;
  bottom: number;
}

