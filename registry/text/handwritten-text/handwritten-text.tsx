interface PlacedStroke {
  d: string;
  /** Offset of the glyph cell this stroke belongs to. */
  x: number;
}

/** Walks the string once, dropping every stroke into place along the baseline. */
function layout(text: string, hand: Hand): { strokes: PlacedStroke[]; width: number } {
  const strokes: PlacedStroke[] = [];
  let x = 0;

  for (const character of text) {
    const glyph = hand.glyphs[character] ?? hand.glyphs[character.toLowerCase()];

    if (!glyph) {
      x += hand.space;
      continue;
    }

    for (const d of glyph.strokes) strokes.push({ d, x });
    x += glyph.advance;
  }

  return { strokes, width: x };
}

interface Point {
  x: number;
  y: number;
}

/**
 * When each stroke is drawn, measured in pen travel rather than in seconds.
 *
 * Timing the strokes by their real length is what keeps the hand steady: a long
 * sweep takes longer than a dot, exactly as it would on paper.
 */
interface Timeline {
  /** Travel at which stroke `i` starts drawing. */
  starts: number[];
  /** Travel at which the pen lifts toward stroke `i`. */
  lifts: number[];
  lengths: number[];
  /** Where the pen leaves the page before stroke `i`, null for the first one. */
  from: (Point | null)[];
  to: Point[];
  total: number;
}

