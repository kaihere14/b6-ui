/**
 * How much bigger the writing is than the type step it sits on.
 *
 * A script this open carries a 0.3em x-height, half what typeset copy has, so
 * matched one to one against the step it would land on four pixels at body
 * size. Drawing it at twice the step puts the x-height back where the eye
 * expects it.
 */
const SCALE = 2;

/** Radius of the nib, in glyph units. */
const NIB_RADIUS = 0.03;

/** Characters written per second when `speed` is left unset. */
const DEFAULT_SPEED = 5;

/** A very short line still gets this long to write. */
const MIN_DURATION = 0.45;

/**
 * How much faster the pen travels while it is off the page.
 *
 * A lift is dead time in the animation, so it is charged at a fraction of the
 * distance: the gap reads as a pause without stalling the line.
 */
const LIFT_SPEED = 2.5;

/** Share of the line spent getting up to speed, and the same again settling. */
const RAMP = 0.12;

/**
 * Pen pace across the line.
 *
 * A hand does not start at full speed and does not stop dead. Velocity ramps up
 * over the first `RAMP` of the line, holds flat through the middle, and ramps
 * back down at the end: the same eased-in, eased-out gesture, with a constant
 * pace in between so no letter is written faster than its neighbour.
 */
function penEase(t: number): number {
  const pace = 1 / (1 - RAMP);

  if (t < RAMP) return (pace * t * t) / (2 * RAMP);
  if (t > 1 - RAMP) {
    const left = 1 - t;
    return 1 - (pace * left * left) / (2 * RAMP);
  }

  return pace * (t - RAMP / 2);
}

/** Room above the ascenders and below the descenders for the ink and the nib. */
const PADDING = 0.06;

/**
 * The drawing surface for one hand.
 *
 * Standing the letters up shears them about the baseline, so the ascenders
 * swing left and the descenders swing right. Both ends of the box pay for it.
 */
function surface(hand: Hand, width: number) {
  const top = hand.top - PADDING;
  const height = hand.bottom + PADDING - top;
  const shift = Math.tan((hand.upright * Math.PI) / 180);
  const lead = Math.abs(top) * shift;

  return {
    top,
    height,
    left: -PADDING - lead,
    width: width + PADDING * 2 + lead + (height + top) * shift,
  };
}

