/**
 * Glyphs live in an em box: x runs left to right, y runs downward from the
 * baseline at 0, and every letter is drawn in the order a hand would draw it.
 *
 * Letters meet where the script says they meet: a lowercase exit and the next
 * letter's entry sit at the same height, so the join falls out of the geometry
 * rather than out of extra code. Where a hand does lift, the letters simply do
 * not touch, and the pen carries itself across the gap.
 */
interface Glyph {
  /** Width of the cell, in em. */
  advance: number;
  /** One entry per pen-down. Two strokes mean the pen lifted between them. */
  strokes: string[];
}

