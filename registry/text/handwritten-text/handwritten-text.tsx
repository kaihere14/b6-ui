/**
 * B6 UI: Handwritten Text
 *
 * Text written by a pen. Every character is a centreline stroke, not an
 * outline, so the component draws the same path a hand would draw: into the
 * letter, around it, out to the join, on to the next one. Nothing fades in and
 * nothing appears whole.
 *
 * The alphabet below is the component. A normal font gives you glyph outlines,
 * and tracing an outline looks like a balloon being inflated rather than a pen
 * moving, so the letters here are centrelines taken from a single-line script:
 *
 *   script: EMS Allure by Sheldon B. Michaels, a single-line drawing of Allura
 *   by Rob Leuschke (TypeSETit), converted to an SVG font by Windell H. Oskay
 *   and shipped with Inkscape's Hershey Text extension. Its polylines were
 *   refitted to cubics here, so the curves stay smooth at any size.
 *
 *   brush: Mistral SingleLine, Copyright 2025 The Mistral SingleLine Project
 *   Authors (https://github.com/isdat-type/Mistral-SingleLine).
 *
 *   Both are licensed under the SIL Open Font License 1.1
 *   (https://scripts.sil.org/OFL) and the paths derived from them stay under the
 *   same licence.
 *
 * This file is standalone by design. It repeats shared styling rather than
 * importing another B6 component, because a registry item has to work in a
 * project that installed nothing else.
 */

/* -------------------------------------------------------------------------- */
/* Styling                                                                     */
/* -------------------------------------------------------------------------- */

/**
 * B6 type steps, written as direct token reads.
 *
 * A named step like `text-body` lands in tailwind-merge's `text-color` group
 * under a stock `cn()`, where it silently deletes an earlier colour utility.
 * Reading the token directly files it under `font-size` for every `cn()`,
 * extended or not, and still loses to a consumer's own `text-lg`.
 *
 * Only the size and the leading are read. The glyphs are drawn rather than
 * typeset, so the weight and tracking a step defines have nothing to act on.
 */
const TYPE = {
  body: "text-(length:--text-body) leading-(--text-body--line-height)",
  h3: "text-(length:--text-h3) leading-(--text-h3--line-height)",
  h1: "text-(length:--text-h1) leading-(--text-h1--line-height)",
} as const;

